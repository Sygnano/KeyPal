def custom_keycodes(via: dict) -> list[dict]:
    out = []
    for c in via.get("customKeycodes") or []:
        title = c.get("name", "")
        name = KEYCHRON_KEYS.get(title.lower()) or "KC_" + re.sub(r"[^A-Z0-9]+", "_", title.upper()).strip("_")
        out.append({"name": name, "label": c.get("shortName") or title, "title": c.get("title") or title})
    return out


def with_custom_values(keymap, custom: list[dict]):
    """Keychron's key names in the stock keymap → this board's values (QK_KB_0 + i); US shifted
    names → their values."""
    if not keymap:
        return keymap
    value = {c["name"]: f"0x{values['QK_KB'] + i:04X}" for i, c in enumerate(custom)}
    value.update({n: f"0x{v:04X}" for n, v in us_shifted.items()})

    def fix(tok: str) -> str:
        return re.sub(r"\b[A-Z][A-Z0-9_]*\b", lambda m: value.get(KEYCHRON_ALIASES.get(m.group(0), m.group(0)), m.group(0)), tok)

    keymap["layers"] = [[fix(t) for t in layer] for layer in keymap["layers"]]
    keymap["encoders"] = [[[fix(t) for t in knob] for knob in layer] for layer in keymap["encoders"]]
    return keymap


