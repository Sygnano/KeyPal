def led_effects(info: dict) -> list:
    """[name, id] of a white board's LED matrix effects: None, then the enabled ones in enum order."""
    enabled = {k.upper() for k, on in info.get("led_matrix", {}).get("animations", {}).items() if on}
    ids = [e for e in LED_EFFECT_ORDER if e in enabled]
    return [["None", 0]] + [[LED_EFFECT_NAMES.get(e, e.title()), i + 1] for i, e in enumerate(ids)]


def effect_options(menus) -> list | None:
    found = []

    def walk(node):
        if isinstance(node, dict):
            c = node.get("content")
            if isinstance(c, list) and len(c) == 3 and c[0] == "id_qmk_rgb_matrix_effect" and node.get("options"):
                found.append(node["options"])
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(menus)
    return found[0] if found else None


def effect_showif(menus, control: str) -> str | None:
    """The `showIf` of a control (e.g. the effect speed), as VIA writes it."""
    found = []

    def walk(node):
        if isinstance(node, dict):
            c = node.get("content")
            if isinstance(c, list) and len(c) == 3 and c[0] == control:
                found.append(node.get("showIf"))
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(menus)
    return found[0] if found else None


def showif_ids(expr: str | None, ids: list[int]) -> list[int]:
    """Which effect ids a VIA `showIf` accepts. The grammar is `{id_qmk_rgb_matrix_effect} OP N`
    joined by && / || with parentheses; translating it to Python and evaluating is exact enough
    for a build script, and keeps the app from carrying a VIA expression parser."""
    if not expr:
        return []
    py = expr.replace("{id_qmk_rgb_matrix_effect}", "e").replace("&&", " and ").replace("||", " or ")
    out = []
    for e in ids:
        try:
            if eval(py, {"__builtins__": {}}, {"e": e}):  # noqa: S307 - a build script, our own string
                out.append(e)
        except Exception:
            return []
    return out


BOARDS_OUT.mkdir(parents=True, exist_ok=True)
for old in BOARDS_OUT.glob("*.json"):
    old.unlink()
index, seen, stats = [], set(), {"json": 0, "c": 0, "layout": 0, "none": 0, "keymap": 0}
# "_via" before "_launcher" (the C3 Pro 8K ships both, same board).
via_files = sorted(KEYCHRON.glob("**/via_json/*.json"), key=lambda p: (p.parent.as_posix(), "launcher" in p.stem, p.stem))
for f in via_files:
    via = lenient_json(f)
    vid, pid = int(via["vendorId"], 16), int(via["productId"], 16)
    if (vid, pid) in seen:
        continue
    seen.add((vid, pid))
    board_id = re.sub(r"_(via|launcher)$", "", f.stem)
    # Unique ids: Keychron reuses names across models (the Q2 Max's files are "q2_ansi_encoder"…).
    kb = f.parent.parent.name
    if not board_id.startswith(kb + "_"):
        board_id = kb + "_" + board_id.split("_", 1)[-1]
    # A key outside the matrix is a mistake in the definition (one JIS layout has one): left out.
    keys = [k for k in kle_keys(via["layouts"]["keymap"]) if k["row"] < via["matrix"]["rows"] and k["col"] < via["matrix"]["cols"]]
    folder = pid_folder.get(pid)
    folders = chain(folder) if folder else [f.parent.parent]
    info = merged_info(folders)
    effects = effect_options(via.get("menus", []))
    features = info.get("features", {})
    lighting = "rgb" if effects or features.get("rgb_matrix") else "white" if features.get("led_matrix") else "none"
    if lighting == "white":
        effects = led_effects(info)
    # Which effects use the speed and the colour, from the VIA definition's own showIf rules (the
    # app used to hard-code the V6 8K's). White boards: the speed is used by every effect but Solid.
    effect_ids = [e[1] for e in effects or []]
    if lighting == "white":
        speed_ids = [e for e in effect_ids if e > 0 and dict(effects).get(e) != "Solid"]
        color_ids = []
    else:
        speed_ids = showif_ids(effect_showif(via.get("menus", []), "id_qmk_rgb_matrix_effect_speed"), effect_ids)
        color_ids = showif_ids(effect_showif(via.get("menus", []), "id_qmk_rgb_matrix_color"), effect_ids)
    leds, source = led_map(folders, info, keys) if lighting != "none" else ([], "none")
    stats[source] += 1
    custom = custom_keycodes(via)
    keymap = with_custom_values(stock_keymap(folders, info, keys), custom) if folder else None
    stats["keymap"] += keymap is not None
    encoders = len({k["encoder"] for k in keys if "encoder" in k})
    board = {
        "id": board_id,
        "name": via["name"],
        "vid": vid,
        "pid": pid,
        "matrix": via["matrix"],
        "encoders": encoders,
        "firmware": folder.relative_to(QMK / "keyboards").as_posix() if folder else None,
        "lighting": lighting,
        # Flashing: at32-dfu, stm32-dfu, wb32-dfu… (QMK's bootloader name).
        "bootloader": info.get("bootloader"),
        "effects": effects or [],
        "mix": any(e[1] == 24 for e in effects or []),
        # Which effects use the speed and the colour (from the VIA definition's showIf rules).
        "speedEffects": speed_ids,
        "colorEffects": color_ids,
        "center": rgb_center(folders, info),
        "customKeycodes": custom,
        "keys": keys,
        "leds": leds,
        "keymap": keymap,
    }
    (BOARDS_OUT / f"{board_id}.json").write_text(json.dumps(board, separators=(",", ":")), encoding="utf-8", newline="\n")
    index.append({k: board[k] for k in ("id", "name", "vid", "pid", "encoders", "firmware", "lighting", "mix", "bootloader")}
                 | {"rows": via["matrix"]["rows"], "cols": via["matrix"]["cols"],
                    # The default layer (Keychron's Win base), for the app's fallback when the
                    # keyboard can't say which layer it is on.
                    "defaultLayer": (keymap or {}).get("defaultLayer", 0)})
index.sort(key=lambda b: b["name"].lower())
(BOARDS_OUT / "index.json").write_text(json.dumps(index, indent=1), encoding="utf-8", newline="\n")
print(f"boards: {len(index)} (LEDs from keyboard.json {stats['json']}, C {stats['c']}, layout {stats['layout']}, none {stats['none']}; stock keymap {stats['keymap']})")
