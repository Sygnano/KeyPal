#!/usr/bin/env python3
"""Regenerate src/qmk/keycodes.generated.ts and src/data/boards/ (every Keychron keyboard: layout,
matrix, knobs, lighting and effects, LED map, stock keymap) from a checkout of
https://github.com/Keychron/qmk_firmware (branch 2025q3; a sparse one with keyboards/keychron is enough).

Usage: python3 scripts/generate_from_qmk.py /path/to/qmk_firmware
"""
import json
import re
import sys
from pathlib import Path

QMK = Path(sys.argv[1] if len(sys.argv) > 1 else "../qmk_firmware")
OUT = Path(__file__).resolve().parent.parent / "src"

# ---------------------------------------------------------------- keycodes
header = (QMK / "quantum/keycodes.h").read_text()
values: dict[str, int] = {}
for name, val in re.findall(r"^\s+([A-Z][A-Z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+),", header, re.M):
    values[name] = int(val, 16)
for name, target in re.findall(r"^\s+([A-Z][A-Z0-9_]*)\s*=\s*([A-Z][A-Z0-9_]*),", header, re.M):
    if target in values:
        values[name] = values[target]

# Keychron custom keycodes (QK_KB_0 ...), only the unconditional ones.
kb_base = values["QK_KB"]
for i, name in enumerate(["KC_LOPTN", "KC_ROPTN", "KC_LCMMD", "KC_RCMMD", "KC_MCTRL",
                          "KC_LNPAD", "KC_TASK", "KC_FILE", "KC_SNAP", "KC_CTANA"]):
    values[name] = kb_base + i
values["KC_SIRI"] = kb_base + 10  # follows KC_CTANA when lock-screen keys are disabled

# US shifted names (KC_TILD = S(KC_GRAVE)…): not keycodes (the app refuses them from users, they
# mislead on other layouts), but stock keymaps use them, so they're resolved there to values.
us_shifted: dict[str, int] = {}
us = (QMK / "quantum/keymap_extras/keymap_us.h").read_text()
for name, target in re.findall(r"^#define\s+(KC_\w+)\s+S\((KC_\w+)\)", us, re.M):
    if target in values:
        us_shifted[name] = 0x0200 | values[target]
for name, target in re.findall(r"^#define\s+(KC_\w+)\s+(KC_\w+)\s*(?://.*)?$", us, re.M):
    if target in us_shifted and name not in us_shifted:
        us_shifted[name] = us_shifted[target]

# Range markers are not keycodes users should see.
skip = re.compile(r"^QK_[A-Z_]+(_MAX)?$")
table = sorted(((n, v) for n, v in values.items()
                if not (skip.match(n) and n.startswith("QK_") and ("_MAX" in n or n in (
                    "QK_BASIC", "QK_MODS", "QK_MOD_TAP", "QK_LAYER_TAP", "QK_LAYER_MOD", "QK_TO",
                    "QK_MOMENTARY", "QK_DEF_LAYER", "QK_TOGGLE_LAYER", "QK_ONE_SHOT_LAYER",
                    "QK_ONE_SHOT_MOD", "QK_LAYER_TAP_TOGGLE", "QK_SWAP_HANDS", "QK_TAP_DANCE",
                    "QK_MAGIC", "QK_MIDI", "QK_SEQUENCER", "QK_JOYSTICK", "QK_PROGRAMMABLE_BUTTON",
                    "QK_AUDIO", "QK_STENO", "QK_MACRO", "QK_CONNECTION", "QK_LIGHTING", "QK_QUANTUM",
                    "QK_KB", "QK_USER", "QK_UNICODEMAP", "QK_UNICODE", "QK_UNICODEMAP_PAIR")))),
               key=lambda t: (t[1], len(t[0])))

lines = ["// Generated by scripts/generate_from_qmk.py from Keychron/qmk_firmware@2025q3. Do not edit.",
         "export const KEYCODE_TABLE: ReadonlyArray<readonly [string, number]> = ["]
lines += [f'  ["{n}", 0x{v:04X}],' for n, v in table]
lines.append("];")
(OUT / "qmk/keycodes.generated.ts").write_text("\n".join(lines) + "\n", newline="\n")
print(f"keycodes: {len(table)} names")

# ---------------------------------------------------------------- boards (every Keychron keyboard)
# One file per VIA definition (each ANSI/ISO/JIS, knob, RGB/white variant has its own USB product
# id): src/data/boards/<id>.json, loaded when that keyboard is plugged in, and an index of all of
# them (src/data/boards/index.json) that the Rust core embeds too.
KEYCHRON = QMK / "keyboards/keychron"
BOARDS_OUT = OUT / "data/boards"


def lenient_json(path: Path):
    """QMK's JSON files allow // comment lines and trailing commas."""
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"^\s*//.*$", "", text, flags=re.M)
    text = re.sub(r",(\s*[}\]])", r"\1", text)
    return json.loads(text)


def kle_keys(rows: list) -> list[dict]:
    """VIA's KLE layout → keys (kle-serial's rules, rotation included). Label 0 is "row,col",
    label 9 "e<n>" marks a knob. Decals (d) are drawings, not keys."""
    keys = []
    cur = {"x": 0.0, "y": 0.0, "r": 0.0, "rx": 0.0, "ry": 0.0}
    for row in rows:
        props: dict = {}
        for item in row:
            if isinstance(item, dict):
                if "r" in item:
                    cur["r"] = item["r"]
                if "rx" in item:
                    cur["rx"] = item["rx"]
                    cur["x"], cur["y"] = item["rx"], cur["ry"]
                if "ry" in item:
                    cur["ry"] = item["ry"]
                    cur["x"], cur["y"] = cur["rx"], item["ry"]
                cur["x"] += item.get("x", 0)
                cur["y"] += item.get("y", 0)
                props.update({k: item[k] for k in ("w", "h", "x2", "y2", "w2", "h2", "d") if k in item})
                continue
            w, h = props.get("w", 1), props.get("h", 1)
            label = item.split("\n")
            m = re.match(r"^\s*(\d+)\s*,\s*(\d+)\s*$", label[0])
            if m and not props.get("d"):
                key = {"row": int(m[1]), "col": int(m[2]), "x": cur["x"], "y": cur["y"], "w": w, "h": h}
                if "w2" in props or "h2" in props:
                    key.update({"x2": props.get("x2", 0), "y2": props.get("y2", 0), "w2": props.get("w2", w), "h2": props.get("h2", h)})
                if cur["r"]:
                    key.update({"r": cur["r"], "rx": cur["rx"], "ry": cur["ry"]})
                if len(label) > 9 and re.match(r"^e\d+$", label[9]):
                    key["encoder"] = int(label[9][1:])
                keys.append(key)
            cur["x"] += w
            props = {}
        cur["y"] += 1
        cur["x"] = cur["rx"]
    return keys


# USB product id → firmware folder, from every keyboard.json / info.json with one.
pid_folder: dict[int, Path] = {}
for f in sorted(list(KEYCHRON.glob("**/keyboard.json")) + list(KEYCHRON.glob("**/info.json"))):
    if "keymaps" in f.parts:
        continue
    try:
        pid = lenient_json(f).get("usb", {}).get("pid")
    except Exception:
        continue
    if pid:
        pid_folder.setdefault(int(pid, 16), f.parent)


def chain(folder: Path) -> list[Path]:
    """The folder and its parents up to the keyboard's own folder, top first."""
    out = []
    while folder != KEYCHRON and KEYCHRON in folder.parents:
        out.append(folder)
        folder = folder.parent
    return out[::-1]


def merged_info(folders: list[Path]) -> dict:
    info: dict = {}
    for d in folders:
        for name in ("info.json", "keyboard.json"):
            if (d / name).exists():
                try:
                    j = lenient_json(d / name)
                except Exception:
                    continue
                for k, v in j.items():
                    if isinstance(v, dict) and isinstance(info.get(k), dict):
                        info[k] = {**info[k], **v}
                    else:
                        info[k] = v
    return info


def c_led_config(folders: list[Path]):
    """g_led_config from the board's C files: [(row, col) or None, (x, y), flags] per LED."""
    for d in folders[::-1]:
        for c in sorted(d.glob("*.c")):
            src = c.read_text(encoding="utf-8", errors="replace")
            m = re.search(r"led_config_t\s+g_led_config\s*=\s*{(.*?)};", src, re.S)
            if not m:
                continue
            block = re.sub(r"//[^\n]*|/\*.*?\*/", "", m.group(1), flags=re.S)
            parts, depth, start = [], 0, 0
            for i, ch in enumerate(block):
                if ch == "{":
                    depth += 1
                    if depth == 1:
                        start = i + 1
                elif ch == "}":
                    depth -= 1
                    if depth == 0:
                        parts.append(block[start:i])
            if len(parts) != 3:
                continue
            key_of = {}
            for r, row in enumerate(re.findall(r"{([^{}]*)}", parts[0])):
                for col, cell in enumerate(x.strip() for x in row.split(",") if x.strip()):
                    if cell.isdigit():
                        key_of[int(cell)] = (r, col)
            points = [(int(x), int(y)) for x, y in re.findall(r"{\s*(\d+)\s*,\s*(\d+)\s*}", parts[1])]
            flags = [int(f) for f in re.findall(r"\d+", parts[2])]
            if not points:
                continue
            return [(key_of.get(i), p, flags[i] if i < len(flags) else 4) for i, p in enumerate(points)]
    return None


def led_map(folders: list[Path], info: dict, keys: list[dict]):
    """LEDs (key, x, y, flags), and where they came from: keyboard.json, the C file, or the layout."""
    layout = info.get("rgb_matrix", {}).get("layout") or info.get("led_matrix", {}).get("layout")
    if layout:
        leds = [(tuple(l["matrix"]) if "matrix" in l else None, (l["x"], l["y"]), l.get("flags", 4)) for l in layout]
        source = "json"
    else:
        leds, source = c_led_config(folders), "c"
    if leds:
        # Only LEDs under a key of this layout (a board's firmware covers every variant's keys).
        present = {(k["row"], k["col"]) for k in keys}
        out = [{"key": f"{k[0]},{k[1]}", "x": p[0], "y": p[1], "flags": f} for k, p, f in leds if k and tuple(k) in present]
        if out:
            return out, source
    # From the drawing: QMK computes positions the same way (key centres scaled to 224 × 64).
    plain = [k for k in keys if "encoder" not in k]
    if not plain:
        return [], "none"
    max_x = max(k["x"] + k["w"] / 2 for k in plain) or 1
    max_y = max(k["y"] + k["h"] / 2 for k in plain) or 1
    min_x = min(k["x"] + k["w"] / 2 for k in plain)
    min_y = min(k["y"] + k["h"] / 2 for k in plain)
    sx = 224 / max(max_x - min_x, 1)
    sy = 64 / max(max_y - min_y, 1)
    return [{"key": f"{k['row']},{k['col']}", "x": round((k["x"] + k["w"] / 2 - min_x) * sx),
             "y": round((k["y"] + k["h"] / 2 - min_y) * sy), "flags": 4} for k in plain], "layout"


def split_args(s: str) -> list[str]:
    """Top-level commas only: LT(1, KC_A) stays one argument."""
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def stock_keymap(folders: list[Path], info: dict, keys: list[dict]):
    """Keychron's own keymap (keymaps/keychron, else via, else default): the legends shown before the
    keyboard is plugged in. None when it can't be read."""
    km = None
    for name in ("keychron", "via", "default"):
        for d in folders[::-1]:
            if (d / "keymaps" / name / "keymap.c").exists():
                km = d / "keymaps" / name / "keymap.c"
                break
        if km:
            break
    if not km:
        return None
    src = re.sub(r"/\*.*?\*/", "", km.read_text(encoding="utf-8", errors="replace"), flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    enum = re.search(r"enum\s+\w*\s*{([^}]*)}", src)
    layer_names = [re.sub(r"=.*", "", n).strip() for n in enum.group(1).split(",") if n.strip()] if enum else []
    layer_idx = {n: i for i, n in enumerate(layer_names)}
    defines = dict(re.findall(r"^#define\s+(\w+)\s+(.+?)\s*$", src, re.M))

    def resolve(tok: str) -> str:
        tok = defines.get(tok, tok)
        tok = {"_______": "KC_TRNS", "XXXXXXX": "KC_NO"}.get(tok, tok)
        return re.sub(r"\b([A-Z_][A-Z0-9_]*)\b", lambda m: str(layer_idx[m.group(1)]) if m.group(1) in layer_idx else m.group(1), tok)

    layouts = {**info.get("layouts", {}), **{a: info.get("layouts", {}).get(t) for a, t in info.get("layout_aliases", {}).items()}}
    layers = []
    for m in re.finditer(r"\[\s*(\w+)\s*\]\s*=\s*(LAYOUT\w*)\s*\(", src):
        # The macro's arguments, up to its closing parenthesis.
        i, depth = m.end(), 1
        while depth and i < len(src):
            depth += {"(": 1, ")": -1}.get(src[i], 0)
            i += 1
        args = [resolve(a) for a in split_args(src[m.end():i - 1])]
        layout = layouts.get(m.group(2))
        if not layout or len(layout.get("layout", [])) != len(args):
            return None
        by_key = {f"{l['matrix'][0]},{l['matrix'][1]}": a for l, a in zip(layout["layout"], args)}
        layers.append((m.group(1), [by_key.get(f"{k['row']},{k['col']}", "") for k in keys]))
    if not layers:
        return None
    knobs = []
    for name, _ in layers:
        e = re.search(rf"\[\s*{name}\s*\]\s*=\s*{{(.*?)}}\s*,?\s*(?=\[|}})", src, re.S)
        knobs.append([list(p) for p in re.findall(r"ENCODER_CCW_CW\(\s*(\w+)\s*,\s*(\w+)\s*\)", e.group(1))] if e else [])
    names = [n for n, _ in layers]
    return {
        # Keychron's Win/Mac switch: Windows' base layer is the default one on Windows.
        "defaultLayer": names.index("WIN_BASE") if "WIN_BASE" in names else 0,
        "layers": [l for _, l in layers],
        "encoders": knobs,
    }


def rgb_center(folders: list[Path], info: dict) -> list[int]:
    for part in ("rgb_matrix", "led_matrix"):
        c = info.get(part, {}).get("center_point")
        if c:
            return list(c)
    for d in folders[::-1]:
        cfg = d / "config.h"
        if cfg.exists():
            m = re.search(r"#define\s+(?:RGB|LED)_MATRIX_CENTER\s*{\s*(\d+)\s*,\s*(\d+)\s*}", cfg.read_text(errors="replace"))
            if m:
                return [int(m[1]), int(m[2])]
    return [112, 32]


